// 1. A simple function that takes a name and returns a greeting
function createGreeting(name) {
    return "Hello, " + name + "! Your JavaScript is working perfectly.";
}

// 2. We store the result of that function in a variable called 'message'
const message = createGreeting("Abhi");

// 3. This prints the message to your terminal or browser console
console.log(message);